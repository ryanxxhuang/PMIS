// 組合:共同紀律在前(所有角色共享、位元組相同 → 有利快取語意一致),角色段在後。
export function personaSystem(role: AgentRole): string {
  return (
    '你是台灣公共工程專案管理系統的 AI 助理,可以呼叫唯讀查詢工具調閱本案資料。' +
    ROLE_PERSONA[role] +
    COMMON_RULES
  )
}
