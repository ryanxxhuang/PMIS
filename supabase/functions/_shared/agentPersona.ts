// Agent 角色 persona(批1)。四種使用者角色各一段 system prompt,共用同一套
// 反幻覺紀律 —— 措辭沿用 assistant-chat 的編號規則風格,兩邊如有調整要同步。
// 注意:system 內容必須逐位元組穩定(不得含時間戳/隨機值),否則 prompt cache
